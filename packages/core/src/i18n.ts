export const MESSAGES: Record<Lang, Record<MessageKey, string>> = { en, ur };

/** A message in the chosen language, with {placeholders} filled in. */
export function t(key: MessageKey, lang: Lang = 'en', vars: Record<string, string | number> = {}): string {
  const text = MESSAGES[lang][key] ?? MESSAGES.en[key];
  return text.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export const direction = (lang: Lang): 'ltr' | 'rtl' => (lang === 'ur' ? 'rtl' : 'ltr');

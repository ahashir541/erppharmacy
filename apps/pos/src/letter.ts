// Udhaar reminder letter: a formal one-page letter on the pharmacy's own letterhead.
// It opens the print window; choose "Microsoft Print to PDF" (or "Save as PDF") to get a PDF,
// then attach it in WhatsApp, or print it on paper.
import { rsShort } from './util.ts';

export interface Letterhead { pharmacy: string; address?: string | null | undefined; phone?: string | null | undefined; number?: string | null | undefined }
export interface LetterFor { name: string; account_number: string; balance: number; days: number; oldest_bill: string | null }

const esc = (s: unknown) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]!));
const longDate = (d: Date) => d.toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });

export function udhaarLetterHtml(h: Letterhead, r: LetterFor, today = new Date()): string {
  const since = r.oldest_bill ? longDate(new Date(`${String(r.oldest_bill).slice(0, 10)}T00:00:00`)) : '';
  const ref = `UR-${r.account_number}-${today.toISOString().slice(0, 10).replace(/-/g, '')}`;
  const contact = [h.address, h.phone && `Tel ${h.phone}`, h.number && h.number !== h.phone && `WhatsApp ${h.number}`].filter(Boolean).map(esc).join(' · ');
  return `<!doctype html><html><head><meta charset="utf-8"><title>Payment reminder - ${esc(r.name)}</title>
<style>
  @page { size: A4; margin: 18mm 20mm; }
  body { font: 11.5pt/1.55 Georgia, 'Times New Roman', serif; color: #1a1f2b; margin: 0; }
  .head { border-bottom: 3px solid #1b1f4b; padding-bottom: 10px; margin-bottom: 26px; }
  .head h1 { font: 700 22pt/1.1 Inter, Arial, sans-serif; color: #1b1f4b; margin: 0 0 4px; letter-spacing: .01em; }
  .head .c { font: 9.5pt Inter, Arial, sans-serif; color: #555; }
  .meta { display: flex; justify-content: space-between; font-size: 10.5pt; margin-bottom: 22px; }
  .to { margin-bottom: 20px; }
  h2 { font: 700 12.5pt Inter, Arial, sans-serif; margin: 0 0 16px; text-transform: uppercase; letter-spacing: .04em; }
  .box { border: 1px solid #c9ccd6; border-radius: 6px; padding: 12px 16px; margin: 18px 0; font-family: Inter, Arial, sans-serif; font-size: 10.5pt; }
  .box div { display: flex; justify-content: space-between; padding: 3px 0; }
  .box .t { font-weight: 700; font-size: 12pt; border-top: 1px solid #c9ccd6; margin-top: 4px; padding-top: 7px; }
  .sign { margin-top: 46px; }
  .sign .line { width: 200px; border-top: 1px solid #333; margin-top: 40px; padding-top: 4px; font-size: 10pt; }
  .foot { position: fixed; bottom: 0; left: 0; right: 0; text-align: center; font: 8pt Inter, Arial, sans-serif; color: #999; }
</style></head><body>
  <div class="head"><h1>${esc(h.pharmacy)}</h1><div class="c">${contact}</div></div>
  <div class="meta"><span>Ref: ${esc(ref)}</span><span>${esc(longDate(today))}</span></div>
  <div class="to">To,<br><strong>${esc(r.name)}</strong><br>Account no. ${esc(r.account_number)}</div>
  <h2>Subject: Reminder of outstanding balance</h2>
  <p>Dear ${esc(r.name)},</p>
  <p>We value your trust in ${esc(h.pharmacy)}. This is a courteous reminder that the following amount remains outstanding on your account with us.</p>
  <div class="box">
    <div><span>Account</span><span>${esc(r.account_number)}</span></div>
    ${since ? `<div><span>Outstanding since</span><span>${esc(since)}</span></div>` : ''}
    <div><span>Days outstanding</span><span>${esc(r.days)} days</span></div>
    <div class="t"><span>Amount due</span><span>${esc(rsShort(Number(r.balance)))}</span></div>
  </div>
  <p>We would be grateful if you could settle this balance at your earliest convenience. Payment may be made in cash at the pharmacy, or by bank transfer, Easypaisa or JazzCash; please share the payment receipt with us.</p>
  <p>If you have already made this payment, kindly disregard this letter. For any query about your account, please contact us${h.phone ? ` at ${esc(h.phone)}` : ''}.</p>
  <p>Thank you for your cooperation.</p>
  <div class="sign">Yours sincerely,<div class="line">For ${esc(h.pharmacy)}</div></div>
  <div class="foot">Generated by Nuskha · nuskhapk.vercel.app</div>
</body></html>`;
}

/** Opens the print window for the letter (Save as PDF to share it on WhatsApp). */
export function printUdhaarLetter(h: Letterhead, r: LetterFor) {
  const frame = document.createElement('iframe');
  frame.style.cssText = 'position:fixed;right:0;bottom:0;width:0;height:0;border:0';
  document.body.appendChild(frame);
  const doc = frame.contentDocument!;
  doc.open(); doc.write(udhaarLetterHtml(h, r)); doc.close();
  window.setTimeout(() => {
    frame.contentWindow?.focus();
    frame.contentWindow?.print();
    window.setTimeout(() => frame.remove(), 60_000);
  }, 250);
}

-- 0028: MedFlow HQ for MedFlow Local (D57). Each pharmacy runs MedFlow on its own PC; MedFlow HQ
-- (this same schema, run by the platform owner) keeps one row per pharmacy in tenants, gives it a
-- licence key, and answers its daily check-in with what it may do: status, plan, features, limits,
-- announcements and invoices. HQ signs the answer (Ed25519) so the pharmacy can trust it offline.
-- HQ never receives the pharmacy's sales, stock or customers: only counts for the health page.

create table licence_keys (
  id          uuid primary key default app.uuid_v7(),
  tenant_id   uuid not null references tenants (id),
  key_sha256  text not null unique,           -- the key itself is shown once and never stored
  key_hint    text not null,                  -- last 4 characters, to recognise it
  created_by  uuid references platform_admins (id),
  created_at  timestamptz not null default now(),
  revoked_at  timestamptz
);
create unique index licence_keys_one_live on licence_keys (tenant_id) where revoked_at is null;

create table local_installs (
  id               uuid primary key,          -- generated by the pharmacy's server on first start
  tenant_id        uuid not null references tenants (id),
  machine          text,
  app_version      text,
  first_seen_at    timestamptz not null default now(),
  last_checkin_at  timestamptz not null default now(),
  checkins         bigint not null default 1,
  stats            jsonb not null default '{}'::jsonb,  -- counts only, never money
  blocked_at       timestamptz,
  blocked_reason   text
);
create index on local_installs (tenant_id, last_checkin_at desc);

alter table licence_keys enable row level security;
alter table local_installs enable row level security;
create policy platform_read on licence_keys for select to authenticated using (app.is_platform_admin());
create policy platform_read on local_installs for select to authenticated using (app.is_platform_admin());

-- A new licence key: MF-XXXX-XXXX-XXXX-XXXX (64 random bits, hex).
create or replace function app.new_licence_key(p_tenant uuid, p_admin uuid) returns text
language plpgsql security definer set search_path = public, app as $$
declare
  raw text := upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 16));
  key text := 'MF-' || substr(raw, 1, 4) || '-' || substr(raw, 5, 4) || '-' || substr(raw, 9, 4) || '-' || substr(raw, 13, 4);
begin
  update licence_keys set revoked_at = now() where tenant_id = p_tenant and revoked_at is null;
  insert into licence_keys (tenant_id, key_sha256, key_hint, created_by)
  values (p_tenant, encode(sha256(convert_to(key, 'UTF8')), 'hex'), right(key, 4), p_admin);
  return key;
end $$;

create or replace function app.licence_key_tenant(p_key text) returns uuid
language sql stable security definer set search_path = public, app as $$
  select tenant_id from licence_keys
  where key_sha256 = encode(sha256(convert_to(upper(trim(p_key)), 'UTF8')), 'hex') and revoked_at is null
$$;

-- The platform owner adds a pharmacy (a customer). It starts on a trial of its plan.
create or replace function public.platform_create_pharmacy(p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  aid uuid := app.platform_admin();
  pl plans;
  tid uuid;
  days int;
begin
  if coalesce(trim(p ->> 'name'), '') = '' then raise exception 'Pharmacy name is required' using errcode = '22023'; end if;
  select * into pl from plans where code = coalesce(p ->> 'plan', 'basic') and archived_at is null;
  if not found then raise exception 'Unknown plan %', p ->> 'plan' using errcode = 'P0002'; end if;
  days := coalesce((p ->> 'trial_days')::int, pl.trial_days);
  insert into tenants (name, owner_name, owner_phone, owner_email, city, status, plan_id, trial_ends_at, offline_licence_days)
  values (trim(p ->> 'name'), coalesce(trim(p ->> 'owner_name'), ''), coalesce(trim(p ->> 'owner_phone'), ''),
          coalesce(nullif(trim(p ->> 'owner_email'), ''), 'pharmacy-' || gen_random_uuid() || '@medflow.local'),
          coalesce(trim(p ->> 'city'), ''), case when days > 0 then 'trial' else 'active' end, pl.id,
          case when days > 0 then now() + make_interval(days => days) end, coalesce((p ->> 'offline_days')::int, 15))
  returning id into tid;
  perform app.platform_log(aid, tid, 'pharmacy_created', p);
  return jsonb_build_object('tenant_id', tid, 'licence_key', app.new_licence_key(tid, aid));
end $$;

-- A new key (the old one stops working at its next check-in), e.g. when a key was shared.
create or replace function public.platform_reissue_licence_key(p_tenant uuid) returns text
language plpgsql security definer set search_path = public, app as $$
declare aid uuid := app.platform_admin();
begin
  if not exists (select 1 from tenants where id = p_tenant) then raise exception 'Pharmacy not found' using errcode = 'P0002'; end if;
  perform app.platform_log(aid, p_tenant, 'licence_key_reissued', '{}');
  return app.new_licence_key(p_tenant, aid);
end $$;

create or replace function public.platform_block_install(p_install uuid, p_blocked boolean, p_reason text default null) returns void
language plpgsql security definer set search_path = public, app as $$
declare aid uuid := app.platform_admin();
begin
  update local_installs set blocked_at = case when p_blocked then now() end, blocked_reason = case when p_blocked then p_reason end
  where id = p_install;
  if not found then raise exception 'Install not found' using errcode = 'P0002'; end if;
  perform app.platform_log(aid, (select tenant_id from local_installs where id = p_install), case when p_blocked then 'install_blocked' else 'install_unblocked' end,
                           jsonb_build_object('install', p_install, 'reason', p_reason));
end $$;

create or replace function public.platform_set_payment_instructions(p_text text) returns void
language plpgsql security definer set search_path = public, app as $$
declare aid uuid := app.platform_admin();
begin
  insert into platform_settings (key, value, updated_by) values ('payment_instructions', to_jsonb(coalesce(p_text, '')), aid)
  on conflict (key) do update set value = excluded.value, updated_by = excluded.updated_by, updated_at = now();
end $$;

-- ---- Console reads ----------------------------------------------------------------------------
create or replace function public.platform_pharmacies() returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
declare aid uuid := app.platform_admin();
begin
  return (select coalesce(jsonb_agg(x order by x.created_at desc), '[]') from (
    select t.id, t.name, t.owner_name, t.owner_phone, t.city, t.status, t.trial_ends_at, t.grace_ends_at, t.read_only_from, t.created_at,
           pl.code plan, pl.name plan_name,
           (select s.price from subscriptions s where s.tenant_id = t.id and s.status <> 'cancelled') price,
           (select s.billing_cycle from subscriptions s where s.tenant_id = t.id and s.status <> 'cancelled') cycle,
           (select max(i.last_checkin_at) from local_installs i where i.tenant_id = t.id) last_checkin_at,
           (select i.app_version from local_installs i where i.tenant_id = t.id order by i.last_checkin_at desc limit 1) app_version,
           (select count(*) from local_installs i where i.tenant_id = t.id)::int installs,
           (select coalesce(sum(amount), 0) from platform_invoices pi where pi.tenant_id = t.id and pi.status in ('due', 'overdue', 'submitted')) unpaid,
           (select k.key_hint from licence_keys k where k.tenant_id = t.id and k.revoked_at is null) key_hint
    from tenants t join plans pl on pl.id = t.plan_id) x);
end $$;

create or replace function public.platform_pharmacy(p_tenant uuid) returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
declare aid uuid := app.platform_admin();
begin
  return (select jsonb_build_object(
    'pharmacy', to_jsonb(t) - 'white_label',
    'plan', (select code from plans where id = t.plan_id),
    'key_hint', (select key_hint from licence_keys where tenant_id = t.id and revoked_at is null),
    'subscription', (select to_jsonb(s) from subscriptions s where s.tenant_id = t.id and s.status <> 'cancelled'),
    'invoices', (select coalesce(jsonb_agg(to_jsonb(i) order by i.period_start desc), '[]') from platform_invoices i where i.tenant_id = t.id),
    'payments', (select coalesce(jsonb_agg(to_jsonb(pm) order by pm.submitted_at desc), '[]') from platform_payments pm where pm.tenant_id = t.id),
    'installs', (select coalesce(jsonb_agg(to_jsonb(i) order by i.last_checkin_at desc), '[]') from local_installs i where i.tenant_id = t.id),
    'features', (select coalesce(jsonb_agg(jsonb_build_object('code', f.code, 'name', f.name, 'module', f.module, 'enabled', x.enabled, 'limit', x.limit_value,
                    'override', (select jsonb_build_object('enabled', o.enabled, 'limit', o.limit_value, 'reason', o.reason) from tenant_feature_overrides o
                                 where o.tenant_id = t.id and o.feature_code = f.code)) order by f.module, f.code), '[]')
                 from features f cross join lateral app.tenant_feature(t.id, f.code) x),
    'log', (select coalesce(jsonb_agg(to_jsonb(l) order by l.occurred_at desc), '[]') from (select * from platform_audit_log where tenant_id = t.id order by occurred_at desc limit 30) l))
  from tenants t where t.id = p_tenant);
end $$;

create or replace function public.platform_plans() returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
declare aid uuid := app.platform_admin();
begin
  return jsonb_build_object(
    'plans', (select coalesce(jsonb_agg(jsonb_build_object('id', p.id, 'code', p.code, 'name', p.name, 'price_monthly', p.price_monthly,
                'price_yearly', p.price_yearly, 'trial_days', p.trial_days, 'is_public', p.is_public, 'sort_order', p.sort_order,
                'features', (select coalesce(jsonb_object_agg(pf.feature_code, jsonb_build_object('enabled', pf.enabled, 'limit', pf.limit_value)), '{}')
                             from plan_features pf where pf.plan_id = p.id)) order by p.sort_order), '[]') from plans p where p.archived_at is null),
    'features', (select coalesce(jsonb_agg(to_jsonb(f) order by f.module, f.code), '[]') from features f),
    'payment_instructions', (select value #>> '{}' from platform_settings where key = 'payment_instructions'));
end $$;

create or replace function public.platform_payments_to_review() returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
declare aid uuid := app.platform_admin();
begin
  return (select coalesce(jsonb_agg(jsonb_build_object('id', pm.id, 'pharmacy', t.name, 'tenant_id', t.id, 'invoice_number', i.invoice_number,
            'invoice_amount', i.amount, 'method', pm.method, 'amount', pm.amount, 'reference', pm.reference, 'submitted_at', pm.submitted_at,
            'status', pm.status) order by pm.submitted_at desc), '[]')
    from platform_payments pm join platform_invoices i on i.id = pm.invoice_id join tenants t on t.id = pm.tenant_id
    where pm.status = 'pending' or pm.submitted_at > now() - interval '30 days');
end $$;

-- ---- The pharmacy's daily check-in (HQ server / Edge Function only, never a browser) ----------
create or replace function public.hq_checkin(p_key text, p_install uuid, p_info jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  tid uuid := app.licence_key_tenant(p_key);
  t tenants;
  pl plans;
  ins local_installs;
  until timestamptz;
  may boolean;
begin
  if tid is null then raise exception 'This licence key is not valid. Ask MedFlow for your key.' using errcode = '42501', hint = 'bad_key'; end if;
  if p_install is null then raise exception 'Install id is required' using errcode = '22023'; end if;
  select * into ins from local_installs where id = p_install;
  if found and ins.tenant_id <> tid then
    raise exception 'This PC belongs to another pharmacy' using errcode = '42501', hint = 'wrong_pharmacy';
  end if;
  insert into local_installs (id, tenant_id, machine, app_version, stats)
  values (p_install, tid, left(p_info ->> 'machine', 100), left(p_info ->> 'version', 30), coalesce(p_info -> 'stats', '{}'))
  on conflict (id) do update set last_checkin_at = now(), checkins = local_installs.checkins + 1,
    machine = excluded.machine, app_version = excluded.app_version, stats = excluded.stats
  returning * into ins;
  select * into t from tenants where id = tid;
  select * into pl from plans where id = t.plan_id;
  may := t.status in ('trial', 'active', 'grace') and ins.blocked_at is null;
  until := now() + make_interval(days => t.offline_licence_days);
  if t.read_only_from is not null then until := least(until, t.read_only_from); end if;
  if t.status = 'trial' and t.trial_ends_at is not null then until := least(until, t.trial_ends_at + interval '1 day'); end if;
  return jsonb_build_object(
    'kind', 'pharmacy', 'tenant_id', t.id, 'install_id', ins.id, 'pharmacy', t.name, 'plan', pl.code, 'plan_name', pl.name,
    'status', case when ins.blocked_at is not null then 'suspended' else t.status end, 'may_sell', may,
    'trial_ends_at', t.trial_ends_at, 'grace_ends_at', t.grace_ends_at, 'read_only_from', t.read_only_from,
    'issued_at', now(), 'valid_until', case when may then until else now() end,
    'features', (select coalesce(jsonb_object_agg(f.code, jsonb_build_object('enabled', x.enabled, 'limit', x.limit_value)), '{}')
                 from features f cross join lateral app.tenant_feature(t.id, f.code) x),
    'announcements', (select coalesce(jsonb_agg(jsonb_build_object('id', a.id, 'title', a.title, 'title_ur', a.title_ur, 'body', a.body,
                        'body_ur', a.body_ur, 'severity', a.severity) order by a.starts_at desc), '[]')
                      from announcements a where a.starts_at <= now() and (a.ends_at is null or a.ends_at > now())
                        and (a.audience = 'all' or (a.audience = 'plan' and a.plan_id = t.plan_id) or (a.audience = 'tenant' and a.tenant_id = t.id))),
    'invoices', (select coalesce(jsonb_agg(jsonb_build_object('id', i.id, 'invoice_number', i.invoice_number, 'amount', i.amount, 'currency', i.currency,
                   'due_at', i.due_at, 'status', i.status) order by i.due_at), '[]')
                 from platform_invoices i where i.tenant_id = t.id and i.status in ('due', 'overdue', 'submitted')),
    'payment_instructions', (select value #>> '{}' from platform_settings where key = 'payment_instructions'));
end $$;

-- The pharmacy says it paid an invoice (by licence key, from its Settings).
create or replace function public.hq_submit_payment(p_key text, p_invoice uuid, p_method text, p_amount bigint, p_reference text) returns uuid
language plpgsql security definer set search_path = public, app as $$
declare
  tid uuid := app.licence_key_tenant(p_key);
  pid uuid;
begin
  if tid is null then raise exception 'This licence key is not valid' using errcode = '42501'; end if;
  if not exists (select 1 from platform_invoices where id = p_invoice and tenant_id = tid and status in ('due', 'overdue', 'submitted')) then
    raise exception 'Invoice not found or already paid' using errcode = 'P0002';
  end if;
  if coalesce(trim(p_reference), '') = '' then raise exception 'Enter the transaction reference' using errcode = '22023'; end if;
  if coalesce(p_amount, 0) <= 0 then raise exception 'Enter the amount paid' using errcode = '22023'; end if;
  insert into platform_payments (tenant_id, invoice_id, method, amount, reference)
  values (tid, p_invoice, p_method, p_amount, trim(p_reference)) returning id into pid;
  update platform_invoices set status = 'submitted' where id = p_invoice and status in ('due', 'overdue');
  return pid;
end $$;


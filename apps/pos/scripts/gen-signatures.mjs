// Reads every migration and writes the parameter names of each public function, so the cloud
// client can call `fn(a, b)` as PostgREST's named `fn({ p_x: a, p_y: b })`.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '../../../packages/db/supabase/migrations');
const sigs = {};
for (const f of readdirSync(dir).filter((x) => x.endsWith('.sql')).sort()) {
  const sql = readFileSync(join(dir, f), 'utf8');
  for (const m of sql.matchAll(/create or replace function public\.([a-z_0-9]+)\s*\(([^)]*)\)/gi)) {
    const params = m[2].split(',').map((p) => p.trim().split(/\s+/)[0]).filter((p) => p && /^p_|^p$|^event$/.test(p));
    sigs[m[1]] = params;
  }
}
const out = `// Generated by scripts/gen-signatures.mjs from the migrations. Do not edit.\nexport const SIGNATURES: Record<string, string[]> = ${JSON.stringify(sigs, null, 2)};\n`;
writeFileSync(join(here, '../src/backend/signatures.ts'), out);
console.log(`${Object.keys(sigs).length} functions`);

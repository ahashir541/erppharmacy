export const POS_MESSAGES: Record<Lang, Record<PosKey, string>> = { en, ur };

type AnyKey = PosKey | keyof (typeof CORE)['en'];

export function tr(key: AnyKey, lang: Lang, vars: Record<string, string | number> = {}): string {
  const text = (POS_MESSAGES[lang] as Record<string, string>)[key] ?? (CORE[lang] as Record<string, string>)[key]
    ?? (POS_MESSAGES.en as Record<string, string>)[key] ?? (CORE.en as Record<string, string>)[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}
